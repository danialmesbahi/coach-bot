import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';

const source=readFileSync(new URL('../src/lib/api.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {api}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const events=[];
globalThis.window={setTimeout,clearTimeout,dispatchEvent:event=>events.push(event.detail)};
globalThis.fetch=async()=>{throw new TypeError('private request body');};
await assert.rejects(api('/api/catalog'));
assert.deepEqual(events.splice(0),[{kind:'NetworkError',requestId:''}]);
await assert.rejects(api('/api/analytics/client-error'));
assert.equal(events.length,0,'reporting failure recursively reports itself');
const cancelled=new AbortController();cancelled.abort();
await assert.rejects(api('/api/catalog','',{signal:cancelled.signal}));
assert.equal(events.length,0,'deliberate cancellation reported as failure');
globalThis.fetch=async()=>new Response(JSON.stringify({error:'internal'}),{status:503,headers:{'X-Request-ID':'a'.repeat(16)}});
await assert.rejects(api('/api/catalog'));
assert.deepEqual(events.splice(0),[{kind:'HttpError',requestId:'a'.repeat(16)}]);
globalThis.fetch=async()=>new Response('proxy error',{status:502,headers:{'X-Request-ID':'secret-password'}});
await assert.rejects(api('/api/catalog'));
assert.deepEqual(events.splice(0),[{kind:'HttpError',requestId:''}]);
globalThis.fetch=async()=>new Response(JSON.stringify({error:'invalid_product'}),{status:400});
await assert.rejects(api('/api/catalog'));
assert.equal(events.length,0,'ordinary validation sent as a runtime failure');
window.setTimeout=callback=>setTimeout(callback,0);
globalThis.fetch=async(_url,{signal})=>new Promise((_resolve,reject)=>signal.addEventListener('abort',()=>reject(new DOMException('timeout','AbortError'))));
await assert.rejects(api('/api/catalog'));
assert.deepEqual(events.splice(0),[{kind:'TimeoutError',requestId:''}]);
console.log('PASS: bounded metadata events for network/HTTP/timeout; no secrets, cancellation noise or recursive reporting');
